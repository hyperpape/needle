package com.justinblank.strings.RegexAST;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.List;
import java.util.Optional;
import java.util.PriorityQueue;

/**
 * A sound over-approximation of the set of lengths that a node can match, represented as a disjunction of
 * {@link LengthPolynomial}s.
 *
 * <p>A single polynomial already over-approximates concatenation and repetition. A union, however, is not a sum of
 * independent terms, so it needs a term of its own. {@link #union(LengthFilter)}, {@link #plus(LengthFilter)} and the
 * repetition operations combine terms while preserving soundness: every string length the node can produce is
 * accepted. Concatenation distributes over the disjunction, so it can multiply the number of terms; analysis is
 * abandoned (returning an empty result) when that count grows past {@link #MAX_TERMS}.
 *
 * <p>For a filter with a single term, the operations delegate to {@link LengthPolynomial} so that expressions without
 * unions behave exactly as before. Only the multi-term membership computation is new.
 */
public class LengthFilter {

    static final int MAX_TERMS = 16;

    private final List<LengthPolynomial> terms;

    private LengthFilter(List<LengthPolynomial> terms) {
        this.terms = terms;
    }

    static Optional<LengthFilter> of(LengthPolynomial polynomial) {
        return Optional.of(new LengthFilter(List.of(polynomial)));
    }

    /**
     * @return the single polynomial backing this filter, if it has only one term
     */
    public Optional<LengthPolynomial> single() {
        return terms.size() == 1 ? Optional.of(terms.get(0)) : Optional.empty();
    }

    Optional<LengthFilter> union(LengthFilter other) {
        var combined = new ArrayList<LengthPolynomial>(terms.size() + other.terms.size());
        combined.addAll(terms);
        combined.addAll(other.terms);
        if (combined.size() > MAX_TERMS) {
            return Optional.empty();
        }
        return Optional.of(new LengthFilter(combined));
    }

    Optional<LengthFilter> plus(LengthFilter other) {
        if (terms.size() == 1 && other.terms.size() == 1) {
            return of(terms.get(0).plus(other.terms.get(0)));
        }
        if ((long) terms.size() * other.terms.size() > MAX_TERMS) {
            return Optional.empty();
        }
        var combined = new ArrayList<LengthPolynomial>(terms.size() * other.terms.size());
        for (var left : terms) {
            for (var right : other.terms) {
                combined.add(left.plus(right));
            }
        }
        return Optional.of(new LengthFilter(combined));
    }

    Optional<LengthFilter> repeat() {
        if (terms.size() == 1) {
            return terms.get(0).multi(0, -1).flatMap(LengthFilter::of);
        }
        // Each repetition contributes one of the terms, so the reachable lengths are the numerical semigroup
        // generated by every term's minimum length and component sizes.
        return of(semigroupOfTerms());
    }

    Optional<LengthFilter> repeatCount(int min, int max) {
        if (terms.size() == 1) {
            if (min == max) {
                return of(terms.get(0).times(min));
            }
            return terms.get(0).multi(min, max).flatMap(LengthFilter::of);
        }
        // A{min,max} is a subset of A*, which is sound and avoids materializing every intermediate cross product.
        return repeat();
    }

    private LengthPolynomial semigroupOfTerms() {
        var result = LengthPolynomial.constant(0);
        for (var term : terms) {
            int offset = term.minLength();
            if (offset > 0) {
                result = result.plus(LengthPolynomial.constant(offset).multi(0, -1).orElseThrow());
            }
            for (int size : term.componentSizes()) {
                if (size > 0) {
                    result = result.plus(LengthPolynomial.constant(size).multi(0, -1).orElseThrow());
                }
            }
        }
        return result;
    }

    /**
     * Compute a periodic membership table for the lengths accepted by this filter, if one is small enough to embed.
     *
     * <p>A filter with a single term uses {@link LengthPolynomial#membership(int)} directly. For a disjunction, each
     * term is treated as an unbounded numerical semigroup rooted at its minimum length, and a shortest-path search
     * finds the least reachable length in each residue class. The union of those classes remains a sound superset of
     * the lengths the node can match.
     */
    public Optional<LengthPolynomial.Membership> membership(int maxModulus) {
        Optional<LengthPolynomial.Membership> membership;
        if (terms.size() == 1) {
            membership = terms.get(0).membership(maxModulus);
        }
        else {
            membership = unionMembership(maxModulus);
        }
        // A modulus of one only restates the minimum length, which the factorization already checks.
        return membership.filter(result -> result.modulus() > 1);
    }

    private Optional<LengthPolynomial.Membership> unionMembership(int maxModulus) {
        int modulus = Integer.MAX_VALUE;
        for (var term : terms) {
            for (int size : term.componentSizes()) {
                modulus = Math.min(modulus, size);
            }
        }
        if (modulus == Integer.MAX_VALUE || modulus > maxModulus) {
            return Optional.empty();
        }

        int[] threshold = new int[modulus];
        Arrays.fill(threshold, Integer.MAX_VALUE);
        for (var term : terms) {
            int[] reachable = shortestReachableLengths(term, modulus);
            for (int residue = 0; residue < modulus; residue++) {
                if (reachable[residue] < threshold[residue]) {
                    threshold[residue] = reachable[residue];
                }
            }
        }

        int base = Integer.MAX_VALUE;
        for (var term : terms) {
            base = Math.min(base, term.minLength());
        }
        int[] minRepresentable = new int[modulus];
        for (int residue = 0; residue < modulus; residue++) {
            int least = threshold[(base + residue) % modulus];
            minRepresentable[residue] = least == Integer.MAX_VALUE ? Integer.MAX_VALUE : least - base;
        }
        return Optional.of(new LengthPolynomial.Membership(base, modulus, minRepresentable));
    }

    private static int[] shortestReachableLengths(LengthPolynomial term, int modulus) {
        int[] reachable = new int[modulus];
        Arrays.fill(reachable, Integer.MAX_VALUE);
        int start = term.minLength();
        int startResidue = start % modulus;
        if (start >= reachable[startResidue]) {
            return reachable;
        }
        reachable[startResidue] = start;
        var queue = new PriorityQueue<long[]>(Comparator.comparingLong(entry -> entry[0]));
        queue.add(new long[] {start, startResidue});
        while (!queue.isEmpty()) {
            var current = queue.poll();
            long value = current[0];
            int residue = (int) current[1];
            if (value > reachable[residue]) {
                continue;
            }
            for (int size : term.componentSizes()) {
                long next = value + size;
                int nextResidue = (int) (next % modulus);
                long clamped = Math.min(next, Integer.MAX_VALUE);
                if (clamped < reachable[nextResidue]) {
                    reachable[nextResidue] = (int) clamped;
                    queue.add(new long[] {next, nextResidue});
                }
            }
        }
        return reachable;
    }
}
